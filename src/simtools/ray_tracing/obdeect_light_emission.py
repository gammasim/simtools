"""Calibration light made and traced by obdeect, handed to sim_telarray.

Flasher and illuminator photons are generated by an obdeect point emitter and
traced to the camera entrance: straight from the flasher to the camera, or
through the optics for an illuminator. The photons at the camera entrance are
written as photon bunches for sim_telarray, which then simulates the camera
and electronics with its optics bypassed (``Bypass_Optics``).

The light-source descriptions (angular distribution, pulse shape) are the
sim_telarray LightEmission arguments simtools derives from the calibration
model, so both backends start from the same input.
"""

import math
from pathlib import Path

import numpy as np

from simtools.simtel.photon_bunch_file import BUNCH_DTYPE

_GAUSS_NODES = 100  # sim_telarray LightEmission: nodes every 0.05 rms up to 5 rms.


def _table(text):
    """Two-column table (first column ascending) from a sim_telarray table file."""
    columns = np.loadtxt(text, comments="#", usecols=(0, 1), ndmin=2)
    return columns[:, 0], columns[:, 1]


def angular_profile(token):
    """Relative intensity versus angle [deg] for a LightEmission angular distribution.

    Parameters
    ----------
    token: str
        ``isotropic``, ``gauss:<rms deg>``, ``filledcone:<half angle deg>`` or
        the name of a table file (angle [deg], relative intensity).

    Returns
    -------
    tuple of numpy.ndarray
        Angles [deg] and relative intensities.
    """
    name, _, value = str(token).lower().partition(":")
    if name == "isotropic":
        return np.array([0.0, 180.0]), np.array([1.0, 1.0])
    if name in ("gauss", "gauss-rms"):
        angles = np.minimum(np.arange(_GAUSS_NODES) * 0.05 * float(value), 180.0)
        return angles, np.exp(-0.5 * (angles / float(value)) ** 2)
    if name == "filledcone":
        cone = float(value)
        return np.array([0.0, cone, cone * (1.0 + 1e-9)]), np.array([1.0, 1.0, 0.0])
    if Path(token).is_file():
        return _table(token)
    raise ValueError(f"angular distribution '{token}' is not supported with obdeect")


def pulse_profile(token):
    """Relative emission rate versus time [ns] for a LightEmission pulse shape.

    Parameters
    ----------
    token: str
        ``simple:<full width ns>``, ``gauss:<rms ns>``, ``exponential:<decay ns>``
        or the name of a table file (time [ns], rate).

    Returns
    -------
    tuple of numpy.ndarray or None
        Times [ns] and rates, or None for an instantaneous pulse.
    """
    name, _, value = str(token).lower().partition(":")
    width = float(value) if value else 0.0
    if name in ("simple", "gauss", "exponential") and width <= 0.0:
        return None
    if name == "simple":
        return np.array([-0.5 * width, 0.5 * width]), np.array([1.0, 1.0])
    if name == "gauss":
        times = np.linspace(-5.0 * width, 5.0 * width, 201)
        return times, np.exp(-0.5 * (times / width) ** 2)
    if name == "exponential":  # Mean time zero, as in sim_telarray.
        times = np.linspace(0.0, 20.0 * width, 401)
        return times - width, np.exp(-times / width)
    if Path(token).is_file():
        return _table(token)
    raise ValueError(f"pulse shape '{token}' is not supported with obdeect")


class AtmosphericTransmission:
    """Vertical optical depths of a sim_telarray atmospheric transmission table.

    The table lists, per integer wavelength, the optical depth from each
    altitude down to the observation level (the first level, depth zero).
    Depths are interpolated linearly in log10(altitude) and clamped at the
    table edges, as in sim_telarray (sim_absorb.c).
    """

    def __init__(self, path):
        lines = Path(path).read_text(encoding="utf-8").splitlines()
        first = next(i for i, line in enumerate(lines) if line.startswith("# H2="))
        observation_km, _, levels = lines[first][len("# H2=") :].partition("H1=")
        observation_km = float(observation_km.strip().rstrip(","))
        self.observation_level_m = 1000.0 * observation_km
        levels_km = [observation_km] + [float(v) for v in levels.split("#")[0].split()]
        self._log_altitude = np.log10(np.array(levels_km) * 1e5)  # [cm]
        rows = [
            [float(v) for v in line.split("#")[0].split()]
            for line in lines[first + 1 :]
            if line.split("#")[0].split() and int(float(line.split()[0])) != 0
        ]
        rows = [row for row in rows if len(row) == len(levels_km)]
        self._wavelength = np.array([int(row[0]) for row in rows])
        self._depth = np.column_stack([np.zeros(len(rows)), np.array([row[1:] for row in rows])])

    def optical_depth(self, wavelength_nm, altitude_m):
        """Vertical optical depth between the observation level and an altitude a.s.l."""
        row = np.clip(int(wavelength_nm), self._wavelength[0], self._wavelength[-1])
        depth = self._depth[row - self._wavelength[0]]
        return np.interp(np.log10(100.0 * np.asarray(altitude_m)), self._log_altitude, depth)

    def transmission(self, wavelength_nm, emission_altitude_m, telescope_altitude_m, airmass):
        """Transmission from the emission point to the telescope along a slant path.

        sim_telarray's formula without the instrument term (sim_telarray adds it).
        Emission below the observation level is not transmitted.
        """
        depth = np.abs(
            self.optical_depth(wavelength_nm, emission_altitude_m)
            - self.optical_depth(wavelength_nm, telescope_altitude_m)
        )
        transmitted = np.exp(-depth * np.asarray(airmass))
        return np.where(
            np.asarray(emission_altitude_m) < self.observation_level_m, 0.0, transmitted
        )


def _rotation(alpha, beta):
    """Return sim_telarray's make_trafo(alpha, beta, 0) rotation (sim_imaging.c).

    Rotation by alpha about z, then by beta about the new y axis. Vectors
    transform as rows: v' = v @ matrix.
    """
    matrix = np.eye(3)
    for angle, (i, j) in ((beta, (2, 0)), (alpha, (0, 1))):
        step = np.eye(3)
        step[i, i] = step[j, j] = math.cos(angle)
        step[i, j], step[j, i] = math.sin(angle), -math.sin(angle)
        matrix = step @ matrix
    return matrix


def ground_to_telescope(point_m, theta_deg, phi_deg, axes_offsets_m=()):
    """Transform a point relative to the telescope position into the telescope frame.

    The ground frame is the CORSIKA/sim_telarray array frame; ``theta_deg``
    and ``phi_deg`` are sim_telarray's telescope_theta and telescope_phi;
    ``axes_offsets_m`` the offsets azimuth-altitude axis and altitude axis -
    optical axis, missing values zero (sim_imaging.c, tel_newdir and
    transform_off).
    """
    offsets = np.zeros(2)
    offsets[: len(axes_offsets_m)] = axes_offsets_m
    theta, phi = math.radians(theta_deg), math.radians(phi_deg)
    point = np.asarray(point_m, dtype=float) @ _rotation(phi, 0.0)
    point[0] -= offsets[0]
    point = point @ _rotation(0.0, -theta)
    point[0] += offsets[1]
    return point


def ground_direction_to_telescope(direction, theta_deg, phi_deg):
    """Transform a direction from the ground frame into the telescope frame."""
    theta, phi = math.radians(theta_deg), math.radians(phi_deg)
    return np.asarray(direction, dtype=float) @ _rotation(phi, -theta)


def camera_bunches(arrivals, wavelength_nm, emission_altitude_m):
    """Photon bunches at the camera entrance of a single-mirror telescope.

    With ``Bypass_Optics``, sim_telarray reads a bunch (x, y) as the camera
    position M (x, y) with M = [[cos r, -sin r], [-sin r, -cos r]] (camera
    rotation r), whereas its own optics give R(-r) (x, y) of the telescope
    frame. Since M R(-r) = diag(1, -1), the hand-off turns the telescope frame
    by pi about x, for any camera rotation: (x, y, z) -> (x, -y, -z).

    Parameters
    ----------
    arrivals: dict
        Detected photons traced by obdeect (telescope frame, metres).
    wavelength_nm: numpy.ndarray
        Their wavelengths.
    emission_altitude_m: float or numpy.ndarray
        Altitude a.s.l. sim_telarray takes as the emission point.

    Returns
    -------
    numpy.ndarray
        Photon bunches (``BUNCH_DTYPE``); the photons per bunch are the weights.
    """
    position, direction = arrivals["position_m"], arrivals["direction"]
    bunches = np.empty(len(position), dtype=BUNCH_DTYPE)
    bunches["x"] = 100.0 * position[:, 0]
    bunches["y"] = -100.0 * position[:, 1]
    bunches["cx"] = direction[:, 0]
    bunches["cy"] = -direction[:, 1]
    bunches["time"] = arrivals["time_ns"]
    bunches["zem"] = 100.0 * np.asarray(emission_altitude_m)
    bunches["photons"] = arrivals["weight"]
    bunches["wavelength"] = wavelength_nm
    return bunches


def light_source_events(
    model,
    emitted,
    *,
    seed,
    position_m,
    profile,
    pulse,
    wavelength_nm,
    emission_altitude_m,
    axis=(0.0, 0.0, 1.0),
    disk=None,
    direct=False,
    transmission=1.0,
):
    """Photon bunches at the camera entrance, one array per light pulse.

    Parameters
    ----------
    model: obdeect.OpticalModel
        Optical model of the telescope.
    emitted: iterable of float
        Photons emitted into 4 pi in each pulse.
    seed: int
        Seed of the emitted photons and their transport.
    position_m, axis: tuple of float
        Emitter position and the axis of its angular profile (telescope frame).
    profile, pulse: tuple of numpy.ndarray
        Angular profile and pulse shape (see ``angular_profile``, ``pulse_profile``).
    wavelength_nm: float
        Wavelength.
    emission_altitude_m: float
        Emission altitude a.s.l. handed to sim_telarray (its transmission).
    disk: tuple, optional
        Target disk (centre, normal, radius [m]); default the telescope entrance.
    direct: bool
        Light emitted inside the telescope, straight to the camera (flasher).
    transmission: float
        Extra transmission factor (atmosphere between source and telescope).

    Yields
    ------
    numpy.ndarray
        Photon bunches (``BUNCH_DTYPE``) of the photons reaching the camera.
    """
    # pylint: disable-next=import-outside-toplevel
    from obdeect.model import DETECTED

    for pulse_number, photons in enumerate(emitted):
        source = model.emitter_photons(
            photons,
            seed=seed,
            first_id=pulse_number << 40,
            position_m=position_m,
            intensity=profile,
            axis=axis,
            pulse=pulse,
            wavelength_nm=wavelength_nm,
            disk=disk,
        )
        traced = model.trace(source, seed=seed, direct=direct)
        kept = (traced["status"] == DETECTED) & (traced["weight"] > 0.0)
        arrivals = {name: values[kept] for name, values in traced.items()}
        arrivals["weight"] = arrivals["weight"] * transmission
        yield camera_bunches(arrivals, source["wavelength_nm"][kept], emission_altitude_m)
